alter table public.profiles
  add column if not exists player_id bigint generated by default as identity,
  add column if not exists robux_balance bigint not null default 0 check (robux_balance >= 0),
  add column if not exists tix_balance bigint not null default 0 check (tix_balance >= 0),
  add column if not exists bc_tier text not null default 'none' check (bc_tier in ('none','builders_club','turbo_builders_club','outrageous_builders_club')),
  add column if not exists bc_daily_claim_at timestamptz;

