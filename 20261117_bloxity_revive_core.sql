  add column if not exists is_gear boolean not null default false;

create table if not exists public.bloxity_admins (
  player_id bigint primary key references public.profiles(player_id) on delete cascade,
  granted_by bigint references public.profiles(player_id),
  created_at timestamptz not null default now()
);
alter table public.bloxity_admins enable row level security;

create table if not exists public.currency_transactions (
  id bigint generated always as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  currency text not null check (currency in ('robux','tix')),
  amount bigint not null check (amount <> 0),
  balance_after bigint not null check (balance_after >= 0),
  transaction_type text not null,
  description text not null default '',
