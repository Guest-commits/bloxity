-- Create a profile automatically for username-only BLOXITY registrations.
create or replace function public.bloxity_handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_username text;
begin
  v_username := trim(coalesce(new.raw_user_meta_data ->> 'username',''));
  if v_username !~ '^[A-Za-z0-9_]{3,20}$' then
    v_username := 'Player_' || substr(replace(new.id::text,'-',''),1,8);
  end if;
  if exists (select 1 from public.profiles p where lower(p.username)=lower(v_username)) then
    v_username := 'Player_' || substr(replace(new.id::text,'-',''),1,8);
  end if;
  insert into public.profiles(id,username)
  values(new.id,v_username)
  on conflict (id) do nothing;
  return new;
end;
$$;
revoke all on function public.bloxity_handle_new_user() from public, anon, authenticated;
drop trigger if exists on_auth_user_created_bloxity on auth.users;
create trigger on_auth_user_created_bloxity
after insert on auth.users
for each row execute function public.bloxity_handle_new_user();

-- First registered profile receives player_id 1 while this empty revival is private.
-- player_id 1 is the root owner; additional admins are explicitly granted by that account.
create or replace function public.is_bloxity_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profiles p
    where p.id = (select auth.uid())
      and (p.player_id = 1 or exists (select 1 from public.bloxity_admins a where a.player_id=p.player_id))
  );
$$;
revoke all on function public.is_bloxity_admin() from public, anon;
grant execute on function public.is_bloxity_admin() to authenticated;

create or replace function public.get_my_platform_status()
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare v jsonb;
begin
  if auth.uid() is null then raise exception 'Debes iniciar sesión.'; end if;
  select jsonb_build_object(
    'player_id',p.player_id,
    'is_admin',(p.player_id=1 or exists(select 1 from public.bloxity_admins a where a.player_id=p.player_id)),
    'is_root',(p.player_id=1),
    'bc_tier',p.bc_tier,
    'robux_balance',p.robux_balance,
    'tix_balance',p.tix_balance,
    'coin_balance',p.coin_balance,
    'bc_daily_claim_at',p.bc_daily_claim_at
  ) into v from public.profiles p where p.id=auth.uid();
  return coalesce(v,'{}'::jsonb);
end;
$$;

create or replace function public.choose_builders_club_tier(p_tier text)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare v_user uuid := auth.uid(); v_hat text;
begin
  if v_user is null then raise exception 'Debes iniciar sesión.'; end if;
  if p_tier not in ('builders_club','turbo_builders_club','outrageous_builders_club') then raise exception 'Nivel no válido.'; end if;
  if exists(select 1 from public.profiles where id=v_user and bc_tier <> 'none') then
    return jsonb_build_object('ok',false,'message','Ya elegiste tu nivel de Builders Club.');
  end if;
  v_hat := case p_tier when 'builders_club' then 'bc_hat_classic' when 'turbo_builders_club' then 'bc_hat_turbo' else 'bc_hat_outage' end;
  update public.profiles set bc_tier=p_tier where id=v_user;
  insert into public.user_inventory(user_id,item_id) values(v_user,v_hat) on conflict do nothing;
  return jsonb_build_object('ok',true,'tier',p_tier,'gift_item',v_hat,'message','Builders Club activado gratis y sombrero añadido al inventario.');
end;
$$;

create or replace function public.claim_builders_club_daily_reward()
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare v_user uuid := auth.uid(); v_tier text; v_last timestamptz; v_balance bigint;
