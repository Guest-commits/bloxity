create or replace function public.admin_grant_admin(p_player_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
begin
  if auth.uid() is null or not exists(select 1 from public.profiles p where p.id=auth.uid() and p.player_id=1) then
    raise exception 'Solo el ID 1 puede otorgar acceso de administrador.';
  end if;
  if not exists(select 1 from public.profiles where player_id=p_player_id) then
    return jsonb_build_object('ok',false,'message','No existe ese ID de jugador.');
  end if;
  if p_player_id=1 then return jsonb_build_object('ok',true,'message','El ID 1 ya es administrador principal.'); end if;
  insert into public.bloxity_admins(player_id,granted_by) values(p_player_id,1) on conflict(player_id) do nothing;
  return jsonb_build_object('ok',true,'message','Acceso de administrador concedido.');
end;
$$;

create or replace function public.admin_revoke_admin(p_player_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
begin
  if auth.uid() is null or not exists(select 1 from public.profiles p where p.id=auth.uid() and p.player_id=1) then
    raise exception 'Solo el ID 1 puede administrar los permisos.';
  end if;
  delete from public.bloxity_admins where player_id=p_player_id and player_id<>1;
  return jsonb_build_object('ok',true,'message','Permiso actualizado.');
end;
$$;

create or replace function public.admin_grant_currency(p_player_id bigint,p_currency text,p_amount bigint,p_reason text default 'Ajuste administrativo')
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare v_user uuid; v_balance bigint;
begin
  if auth.uid() is null or not public.is_bloxity_admin() then raise exception 'No tienes permisos de administrador.'; end if;
  if p_currency not in ('robux','tix') or p_amount < 1 or p_amount > 1000000 then raise exception 'Moneda o cantidad no válida.'; end if;
  select id into v_user from public.profiles where player_id=p_player_id for update;
  if v_user is null then return jsonb_build_object('ok',false,'message','No existe ese ID de jugador.'); end if;
  if p_currency='robux' then
    update public.profiles set robux_balance=robux_balance+p_amount where id=v_user returning robux_balance into v_balance;
  else
    update public.profiles set tix_balance=tix_balance+p_amount where id=v_user returning tix_balance into v_balance;
  end if;
  insert into public.currency_transactions(user_id,currency,amount,balance_after,transaction_type,description)
  values(v_user,p_currency,p_amount,v_balance,'admin_grant',left(coalesce(p_reason,'Ajuste administrativo'),120));
  return jsonb_build_object('ok',true,'balance',v_balance);
end;
$$;

