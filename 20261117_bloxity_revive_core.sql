create or replace function public.purchase_catalog_item(p_item_id text)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare v_user uuid := auth.uid(); v_price bigint; v_tier text; v_balance bigint;
begin
  if v_user is null then raise exception 'Debes iniciar sesión.'; end if;
  select price,bc_tier_required into v_price,v_tier from public.catalog_items where item_id=p_item_id and active=true;
  if not found then return jsonb_build_object('ok',false,'message','Artículo no disponible.'); end if;
  if v_tier is not null and not exists(select 1 from public.profiles where id=v_user and bc_tier=v_tier) then
    return jsonb_build_object('ok',false,'message','Este sombrero es un regalo exclusivo de su nivel de Builders Club.');
  end if;
  if exists(select 1 from public.user_inventory where user_id=v_user and item_id=p_item_id) then return jsonb_build_object('ok',false,'message','Ya tienes este artículo.'); end if;
  update public.profiles set coin_balance=coin_balance-v_price where id=v_user and coin_balance>=v_price returning coin_balance into v_balance;
  if v_balance is null then return jsonb_build_object('ok',false,'message','No tienes suficientes BloxCoins.'); end if;
  insert into public.user_inventory(user_id,item_id) values(v_user,p_item_id);
  insert into public.wallet_transactions(user_id,transaction_type,amount,balance_after,description)
  values(v_user,'purchase',-v_price,v_balance,'Compra: '||p_item_id);
  return jsonb_build_object('ok',true,'price',v_price,'coin_balance',v_balance);
end;
$$;

